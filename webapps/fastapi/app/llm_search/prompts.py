"""LLM에게 줄 지시문을 만든다. 순수 함수다.

어댑터 안에 문자열을 인라인하지 않는 이유는 **계약 문구를 테스트로 검증하기
위해서다.** 프롬프트와 `planning.py`의 검증 규칙은 한 쌍이라, 한쪽만 바뀌면
모델이 규격에 맞는 답을 내도 422가 된다.

시각대를 여기서 다룬다. 사용자는 "오늘 6시"처럼 한국 시각으로 말하고 저장소는
UTC로 조회한다. **그 변환을 모델에게 시키지 않는다.**

## 왜 없는 강의실을 null로 만들지 않는가

이전 지시문은 "목록에 없는 곳을 말했으면 null"이었다. 그러면 **"B동 305호"를 물은
사람과 아무 곳도 말하지 않은 사람이 서버에서 같아진다.** null은 `service.py`에서
"전체 카메라"로 해석되므로, 없는 강의실을 물은 사용자는 안내 대신 엉뚱한 전체
결과를 받는다. 등록되지 않았다는 사실을 알려 줄 자리가 사라지는 것이다.

그래서 **들은 이름을 그대로 옮기게 하고, 목록과 대조하는 일은 서버가 한다.**
`_resolve_targets`가 이미 그 판정과 안내 문구를 갖고 있다. 모델이 옮겨 적은 값은
`planning.py`의 문자열 검증과 길이 상한을 거치고, 저장소 조회도 문자열 동등 비교라
그대로 흘러가도 위험하지 않다.

"식별자를 지어내지 마라"와 다른 요구다. 지어내기는 **목록에 있는 값을 임의로 바꾸는
것**이고, 여기서 요구하는 것은 들은 말을 옮기는 것이다.

## 왜 강의실 코드와 이름을 목록에 함께 넣는가

`classroom_id`가 UUID이기 때문이다. 사용자는 "A111"이라고 부르는데 목록에
`f5a51e8e-...`만 있으면 모델이 둘을 이을 방법이 없다. 2026-08-23 실측에서
"A111 강의실에 오늘 몇 명 있었어?"에 모델이 `classroom_id="A111"`을 냈고, 위
규칙대로 들은 이름을 옮긴 값이라 서버는 등록되지 않은 강의실로 판정해 0건을 냈다.
**모델도 서버도 규격을 지켰는데 답이 틀린다.** 이을 근거를 프롬프트가 주지 않은 것이
원인이라 여기서 고친다.

## 남은 한계 — 등록되지 않은 강의실을 등록된 곳으로 오인한다

강의실 이름을 목록에 실은 뒤 생긴 부작용이다. 2026-08-23 실측(gemma, 강의실 하나가
등록된 상태): "B203에 오늘 누가 있었어?"에 모델이 목록의 유일한 `classroom_id`를 냈다.
"목록에 하나만 있어도 그것으로 바꾸지 마라"를 지시문에 넣고 다시 측정했으나 **결과는
같았다.** 작은 모델이 유일한 후보로 끌리는 것을 문장으로 막지 못했다.

서버에서 되돌릴 방법도 마땅치 않다. 모델이 낸 값은 실재하는 식별자라 검증을 통과하고,
"사용자가 그 강의실을 말했는가"를 판정하려면 질문 문자열을 다시 해석해야 하는데 그것은
이 기능이 LLM에게 맡긴 일이다. 규칙을 두 벌로 만들면 화면의 결과가 어느 쪽에서 나온
것인지 알 수 없게 된다.

**그래서 지금은 화면이 대상을 밝히는 것으로 대응한다.** "이렇게 이해했습니다"에 해석한
강의실 이름이 언제나 나오므로, 사용자는 자기가 물은 곳과 다르다는 것을 결과와 함께 본다.
강의실이 늘어난 뒤 다시 측정할 값이다.

## 왜 오전·오후를 지시문이 정하는가

한국어는 "3시"에 오전인지 오후인지를 담지 않는다. 이전 지시문은 "들은 그대로
적어라"였고 예시도 `"6시" -> 06:00`이라, 모델은 언제나 오전으로 읽었다. 2026-08-23
실측: "오늘 3시부터 4시 사이에 강의실에 몇 명이 있었어?"가 03:00~04:00 KST로
해석돼 빈 결과가 나왔다. 같은 질문에 "오후"를 붙이면 15:00을 정확히 냈다.

**이 실패는 검증이 잡지 못한다.** 03:00도 형식상 완벽한 시각이라 `planning.py`를
그대로 통과하고, 사용자는 "그 시간에 아무도 없었다"는 답을 받는다. 강의실을 쓰는
시간대가 낮이라 오후로 읽는 편이 거의 언제나 맞고, 어긋났을 때 알아챌 수 있도록
화면은 해석한 구간을 한국 시각으로 보여준다.

## 왜 분·초를 따로 못 박는가

2026-08-25 실측: "어제 16시 30분부터 17시 사이에 강의실에 박무현 없는 스냅샷"이
16:00~17:00으로 해석됐다. 이전 지시문의 예시가 전부 정시(`06:00`, `15:00`)뿐이라
모델이 "시"만 읽고 "분"을 버린 것이다. **이 실패도 검증이 잡지 못한다** — 16:00은
형식상 완벽한 시각이라 `planning.py`를 그대로 통과하고, 사용자는 자기가 묻지 않은
30분을 포함한 결과를 맞는 답으로 읽는다.

그래서 분·초 규칙을 오전·오후 규칙과 같은 자리에 두고, 예시도 정시가 아닌 값으로
적는다. "반"(16시 반)까지 넣은 것은 그것이 분을 말하는 흔한 방식이기 때문이다.

## 왜 어제 날짜를 우리가 세어 주는가

`tomorrow_kst`를 넘기게 된 것과 같은 이유다. "어제"는 이 기능에서 가장 흔한 기간
표현인데, 모델에게 날짜 뺄셈을 시키면 월초(9월 1일의 어제)에 틀린다. 우리가 이미
아는 값을 계산해 주면 모델이 하는 일은 "어제"라는 단어를 알아보는 것까지로 줄어든다.

## 왜 사람 이름을 위한 칸을 따로 만드는가

칸이 없으면 모델은 이름을 **장소 칸에 넣는다.** 위의 "목록에 없으면 들은 이름을
그대로 classroom_id에 적어라"가 그렇게 시키기 때문이다. 2026-08-25 실측에서
"박무현 없는 스냅샷"이 `classroom_id="박무현"`으로 나왔고, 서버는 등록되지 않은
강의실로 판정해 0건과 함께 "강의실 박무현에 사용 중인 카메라가 없습니다"를 냈다.
**모델도 서버도 규격을 지켰는데 답이 틀리고, 안내 문구까지 엉뚱해진다.**

방향("있는"/"없는")을 함께 받는 이유는 그것이 결과를 뒤집기 때문이다. 이름만 뽑으면
"박무현이 있는 사진"과 "박무현이 없는 사진"이 서버에서 같은 질의가 된다.

## 왜 모델에게 9시간을 빼게 하지 않는가

이전 지시문은 "KST에서 9시간을 빼서 UTC로 적어라"였다. 작은 모델이 가장 자주 틀리는
종류의 작업이고, 특히 자정을 넘길 때(06:00 KST → 전날 21:00 UTC) 날짜를 그대로 두는
실패가 흔하다. 더 나쁜 것은 **검증이 이 실패를 잡지 못한다는 점이다.** 9시간 어긋난
값도 형식상 완벽한 ISO 8601이라 `planning.py`를 그대로 통과하고, 사용자는 조용히
빈 결과를 받는다.

그래서 모델에게는 **들은 시각을 그대로 적고 `+09:00`만 붙이라고** 요구한다. 산술이
`datetime.astimezone`으로 옮겨 가고, 모델이 하는 일은 "6시"를 알아보는 것까지로
줄어든다. 검증은 바뀌지 않는다 — `_required_datetime`이 이미 어떤 오프셋이든 UTC로
정규화하므로, 모델이 굳이 UTC로 답해도 정답이면 통과한다.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import datetime, timedelta
from zoneinfo import ZoneInfo

from .models import CameraChoice

# app/video_monitoring/service.py와 같은 값을 쓴다. 이 서비스가 다루는 강의실이
# 한국에 있다는 사실은 설정이 아니라 전제다.
KST = ZoneInfo("Asia/Seoul")

_INSTRUCTION = """\
너는 강의실 모니터링 시스템의 검색 조건 변환기다.
사용자의 한국어 질문을 읽고 **JSON 객체 하나만** 출력한다.

설명, 인사, 코드펜스(```), 여는 괄호 앞뒤의 어떤 글자도 쓰지 마라.

출력 형식:
{{"intent":"detection_search","camera_id":null,"classroom_id":null,"from":"...","to":"...","limit":20,"person_name":null,"person_presence":"any"}}

규칙:
- intent는 항상 "detection_search"다. 다른 값을 쓰지 마라.
- from, to는 **사용자가 말한 한국 시각을 그대로 적고 뒤에 +09:00을 붙인다.**
- **시각대를 변환하지 마라.** 9시간을 빼지도 더하지도 말고 한국 시각 그대로 적는다.
- **분과 초를 말했으면 그대로 옮긴다. 시각을 정시로 반올림하지 마라.**
  "16시 30분"은 16:30:00이고 "16시 30분 20초"는 16:30:20이다.
  분을 말하지 않았을 때만 00분, 초를 말하지 않았을 때만 00초다.
  "16시 반"은 16:30:00이다.
- **오전인지 오후인지 밝히지 않은 1시~11시는 오후로 읽는다.**
  예) "3시부터 4시" -> "{today_kst}T15:00:00+09:00" ~ "{today_kst}T16:00:00+09:00"
  "오전 3시", "새벽 3시", "아침 3시"처럼 오전을 밝혔을 때만 "{today_kst}T03:00:00+09:00"이다.
  "12시"는 낮 12:00이고, "밤 12시"와 "자정"은 00:00이다.
- 날짜는 아래 값을 그대로 쓴다. 직접 세지 마라.
  "어제"는 {yesterday_kst}, "오늘"은 {today_kst}, "내일"은 {tomorrow_kst}다.
  예) "어제 16시 30분부터 17시 사이"
  -> from "{yesterday_kst}T16:30:00+09:00", to "{yesterday_kst}T17:00:00+09:00"
- from은 to보다 앞서야 한다. 같으면 안 된다.
- to는 구간의 끝이며 그 시각 자체는 포함되지 않는다. "6시부터 7시 사이"는 06:00~07:00이다.
- 기간을 말하지 않았으면 오늘 하루로 잡는다.
  from은 "{today_kst}T00:00:00+09:00", to는 "{tomorrow_kst}T00:00:00+09:00"이다.
  **지금 시각을 from에 적지 마라.** "오늘"은 오늘 0시부터이지 지금부터가 아니다.
- "이번 주"처럼 여러 날을 뜻하면 from을 그 첫날 00:00으로 적는다. 지금 시각이 아니다.
- limit은 1 이상 {max_limit} 이하의 정수다. 말하지 않았으면 {max_limit}을 쓴다.
- 위 여덟 개 말고 다른 키를 넣지 마라.

사람 이름을 말했으면 person_name에 그 이름만 적는다.
**사람 이름을 classroom_id나 camera_id에 넣지 마라.** 그 두 칸은 장소 전용이다.
person_presence는 그 사람이 있어야 하는지 없어야 하는지다.
- "박무현이 있는", "박무현이 나온", "박무현을 찾아줘" -> "present"
- "박무현이 없는", "박무현이 안 보이는", "박무현이 부재중인", "박무현 빼고" -> "absent"
- 사람을 말하지 않았으면 person_name은 null, person_presence는 "any"다.
예) "어제 16시 30분부터 17시 사이에 강의실에 박무현 없는 스냅샷"
-> person_name "박무현", person_presence "absent", classroom_id null

강의실이나 카메라를 말했으면 아래 목록에서 찾는다.
**괄호 안은 그 강의실을 부르는 이름이다.** 사용자가 말한 이름이 괄호 안에 **그대로
있을 때만** 괄호 앞의 classroom_id를 쓴다. 이름 자체를 classroom_id에 적지 마라.

**사용자가 말한 이름이 괄호 안에 없으면, 들은 이름을 그대로 classroom_id에 적는다.**
목록에 하나만 있어도 그것으로 바꾸지 마라. 비슷해 보여도 바꾸지 마라.
목록에 없다고 판단해 null로 바꾸지도 마라 — 등록되지 않았다는 안내는 서버가 한다.
**아무 곳도 말하지 않았을 때만 null이다.**
목록에 있는 식별자를 임의로 바꾸거나 섞지 마라. 목록에 없는 식별자를 지어내지 마라.

**camera_id는 사용자가 카메라를 콕 집어 말했을 때만 채운다. 그 밖에는 언제나 null이다.**
강의실만 말했으면 camera_id는 null이다 — 한 강의실에 카메라가 여러 대라, 네가 하나를
고르면 나머지 카메라에 찍힌 기록이 통째로 빠진다.
camera_id에는 아래 "camera_id=" 바로 뒤의 값만 쓴다. 카메라를 부르는 이름을 적지 마라.
{camera_lines}

지금 시각: {now_kst}
오늘 날짜: {today_kst}\
"""


_RETRY_SUFFIX = """

**직전 응답이 규격을 벗어났다.** 이번에는 JSON 객체 하나만, 위에 적힌 키만 써서
출력하라. 설명도 코드펜스도 붙이지 마라."""


def build_system_prompt(
    *,
    now: datetime,
    cameras: Sequence[CameraChoice],
    max_limit: int,
    retry: bool = False,
) -> str:
    """모델에게 줄 지시문을 만든다.

    `now`는 호출자가 한 번만 구해서 넘긴다. 프롬프트의 "지금"과 검증의 "지금"이
    다른 값이면 경계 시각에서 결과가 어긋난다.

    **"지금"을 한국 시각으로만 알려준다.** UTC를 함께 주면 모델이 그쪽으로 변환하려
    들고, 그 변환이 이 기능에서 없애려는 실패 그 자체다.

    `max_limit`은 호출자가 요청한 상한과 같은 값이어야 한다. 지시문이 허용한 수를
    검증이 되돌려 깎으면, 모델은 규격을 지켰는데 결과가 줄어든 것처럼 보인다.

    `retry`는 직전 응답이 규격을 벗어났을 때 켠다. **모델이 뱉은 원문은 넣지 않는다.**
    되돌려 넣어 봐야 같은 실수를 다시 읽게 만들 뿐이고, 프롬프트를 모델 출력으로
    오염시키는 경로가 된다. 규격을 다시 못 박는 문장 하나면 족하다.
    """
    now_kst = now.astimezone(KST)
    instruction = _INSTRUCTION.format(
        max_limit=max_limit,
        camera_lines=_format_cameras(cameras),
        now_kst=now_kst.strftime("%Y-%m-%d %H:%M:%S"),
        today_kst=now_kst.strftime("%Y-%m-%d"),
        # 다음 날짜도 우리가 계산해서 넘긴다. 모델에게 "다음날"이라고만 말하면
        # 그 한 걸음을 건너뛴다 — 2026-08-23 실측에서 "A111 강의실에 오늘 몇 명
        # 있었어?"에 from과 to를 둘 다 같은 날 00:00으로 냈고, `EMPTY_RANGE`로
        # 거절돼 사용자는 아무 잘못 없이 질문을 고치라는 안내를 받았다.
        tomorrow_kst=(now_kst + timedelta(days=1)).strftime("%Y-%m-%d"),
        # 어제도 같은 이유로 우리가 센다. "어제"는 이 기능에서 가장 흔한 기간
        # 표현인데, 모델에게 날짜 뺄셈을 맡기면 월초에 전월 말일을 틀린다.
        yesterday_kst=(now_kst - timedelta(days=1)).strftime("%Y-%m-%d"),
    )
    return instruction + _RETRY_SUFFIX if retry else instruction


def _format_cameras(cameras: Sequence[CameraChoice]) -> str:
    if not cameras:
        # 등록된 카메라가 없을 때 빈 목록을 그대로 보여주면 모델이 빈칸을 채우려
        # 든다. 사용할 수 있는 값이 null뿐이라고 분명히 말한다.
        return "등록된 카메라가 없다. camera_id와 classroom_id는 반드시 null로 둔다."
    return "\n".join(_camera_line(camera) for camera in cameras)


def _camera_line(camera: CameraChoice) -> str:
    """카메라 한 대를 한 줄로 적는다. **강의실을 부르는 이름을 함께 적는다.**

    `classroom_id`는 UUID라 사용자의 질문에 절대 등장하지 않는다. 코드와 이름이
    같은 줄에 없으면 모델은 "A111"을 UUID로 옮길 근거가 없어, 들은 이름을 그대로
    `classroom_id`에 적는다 — 프롬프트가 그렇게 시키기 때문이다. 그러면 등록된
    강의실을 물어도 등록되지 않은 곳으로 판정된다.
    """
    names = " ".join(part for part in (camera.classroom_code, camera.classroom_name) if part)
    classroom = f"classroom_id={camera.classroom_id}"
    if names:
        classroom += f" ({names})"
    return f"- camera_id={camera.camera_id} / {classroom} / {camera.label}"
